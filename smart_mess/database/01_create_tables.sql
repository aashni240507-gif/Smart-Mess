-- Safe cleanup: drop tables in reverse dependency order if they exist
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN 
              ('WASTAGE', 'COMPLAINTS', 'COMPLAINT_CATEGORIES', 'FEEDBACK', 
               'ATTENDANCE', 'MENU', 'MEAL_TYPES', 'USERS')) 
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
        DBMS_OUTPUT.PUT_LINE('Dropped existing table: ' || t.table_name);
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- TABLE 1: USERS
-- Stores student, mess staff, and administrator account information.
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    USER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME            VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(150) NOT NULL CONSTRAINT UQ_USERS_EMAIL UNIQUE,
    PASSWORD_HASH   VARCHAR2(255) NOT NULL,
    ROLE            VARCHAR2(20)  DEFAULT 'STUDENT' NOT NULL 
                    CONSTRAINT CHK_USERS_ROLE CHECK (ROLE IN ('STUDENT', 'STAFF', 'ADMIN')),
    HOSTEL          VARCHAR2(50),
    ROOM_NO         VARCHAR2(20),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

PROMPT Table USERS created successfully.

-- ----------------------------------------------------------------------------
-- TABLE 2: MEAL_TYPES
-- Lookup table for meal categories (Breakfast, Lunch, Dinner).
-- ----------------------------------------------------------------------------
CREATE TABLE MEAL_TYPES (
    MEAL_TYPE_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MEAL_NAME       VARCHAR2(50) NOT NULL CONSTRAINT UQ_MEAL_TYPES_NAME UNIQUE
);

PROMPT Table MEAL_TYPES created successfully.

-- ----------------------------------------------------------------------------
-- TABLE 3: MENU
-- Daily food schedules for each meal type.
-- ----------------------------------------------------------------------------
CREATE TABLE MENU (
    MENU_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MENU_DATE       DATE NOT NULL,
    MEAL_TYPE_ID    NUMBER NOT NULL,
    FOOD_ITEMS      VARCHAR2(500) NOT NULL,
    NOTES           VARCHAR2(255),
    CONSTRAINT FK_MENU_MEAL_TYPE FOREIGN KEY (MEAL_TYPE_ID) 
        REFERENCES MEAL_TYPES(MEAL_TYPE_ID),
    CONSTRAINT UQ_MENU_DATE_MEAL UNIQUE (MENU_DATE, MEAL_TYPE_ID)
);

-- Index on menu date for fast filtering by date in daily views
CREATE INDEX IDX_MENU_DATE ON MENU(MENU_DATE);

PROMPT Table MENU created successfully.

-- ----------------------------------------------------------------------------
-- TABLE 4: ATTENDANCE
-- Tracks whether a student intends to eat or ate a specific meal.
-- ----------------------------------------------------------------------------
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL,
    MENU_ID         NUMBER NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'PRESENT' NOT NULL 
                    CONSTRAINT CHK_ATTENDANCE_STATUS CHECK (STATUS IN ('PRESENT', 'ABSENT')),
    MARKED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ATTENDANCE_USER FOREIGN KEY (USER_ID) 
        REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ATTENDANCE_MENU FOREIGN KEY (MENU_ID) 
        REFERENCES MENU(MENU_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_ATTENDANCE_USER_MENU UNIQUE (USER_ID, MENU_ID)
);

-- Indexes for quick attendance lookups by user and menu
CREATE INDEX IDX_ATTENDANCE_USER ON ATTENDANCE(USER_ID);
CREATE INDEX IDX_ATTENDANCE_MENU ON ATTENDANCE(MENU_ID);

PROMPT Table ATTENDANCE created successfully.

-- ----------------------------------------------------------------------------
-- TABLE 5: FEEDBACK
-- Ratings (1 to 5) and reviews submitted by students for each meal.
-- ----------------------------------------------------------------------------
CREATE TABLE FEEDBACK (
    FEEDBACK_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL,
    MENU_ID         NUMBER NOT NULL,
    FOOD_QUALITY    NUMBER(1) NOT NULL 
                    CONSTRAINT CHK_FEEDBACK_QUALITY CHECK (FOOD_QUALITY BETWEEN 1 AND 5),
    TASTE           NUMBER(1) NOT NULL 
                    CONSTRAINT CHK_FEEDBACK_TASTE CHECK (TASTE BETWEEN 1 AND 5),
    CLEANLINESS     NUMBER(1) NOT NULL 
                    CONSTRAINT CHK_FEEDBACK_CLEAN CHECK (CLEANLINESS BETWEEN 1 AND 5),
    COMMENTS        VARCHAR2(500),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_FEEDBACK_USER FOREIGN KEY (USER_ID) 
        REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_FEEDBACK_MENU FOREIGN KEY (MENU_ID) 
        REFERENCES MENU(MENU_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_FEEDBACK_MENU ON FEEDBACK(MENU_ID);

PROMPT Table FEEDBACK created successfully.

-- ----------------------------------------------------------------------------
-- TABLE 6: COMPLAINT_CATEGORIES
-- Lookup table for categorized mess grievances.
-- ----------------------------------------------------------------------------
CREATE TABLE COMPLAINT_CATEGORIES (
    CATEGORY_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME   VARCHAR2(50) NOT NULL CONSTRAINT UQ_COMPLAINT_CAT_NAME UNIQUE
);

PROMPT Table COMPLAINT_CATEGORIES created successfully.

-- ----------------------------------------------------------------------------
-- TABLE 7: COMPLAINTS
-- Grievances filed by students with lifecycle tracking (PENDING -> RESOLVED).
-- ----------------------------------------------------------------------------
CREATE TABLE COMPLAINTS (
    COMPLAINT_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL,
    CATEGORY_ID     NUMBER NOT NULL,
    DESCRIPTION     VARCHAR2(1000) NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'PENDING' NOT NULL 
                    CONSTRAINT CHK_COMPLAINTS_STATUS CHECK (STATUS IN ('PENDING', 'IN_PROGRESS', 'RESOLVED')),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    RESOLVED_AT     TIMESTAMP,
    CONSTRAINT FK_COMPLAINTS_USER FOREIGN KEY (USER_ID) 
        REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMPLAINTS_CAT FOREIGN KEY (CATEGORY_ID) 
        REFERENCES COMPLAINT_CATEGORIES(CATEGORY_ID)
);

CREATE INDEX IDX_COMPLAINTS_STATUS ON COMPLAINTS(STATUS);
CREATE INDEX IDX_COMPLAINTS_USER ON COMPLAINTS(USER_ID);

PROMPT Table COMPLAINTS created successfully.

-- ----------------------------------------------------------------------------
-- TABLE 8: WASTAGE
-- Daily food preparation and wastage metrics in kilograms.
-- ----------------------------------------------------------------------------
CREATE TABLE WASTAGE (
    WASTAGE_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MENU_ID         NUMBER NOT NULL,
    FOOD_PREPARED   NUMBER(8,2) NOT NULL CONSTRAINT CHK_WASTAGE_PREP CHECK (FOOD_PREPARED >= 0),
    FOOD_SERVED     NUMBER(8,2) NOT NULL CONSTRAINT CHK_WASTAGE_SERV CHECK (FOOD_SERVED >= 0),
    FOOD_WASTED     NUMBER(8,2) NOT NULL CONSTRAINT CHK_WASTAGE_WAST CHECK (FOOD_WASTED >= 0),
    RECORDED_BY     NUMBER NOT NULL,
    RECORDED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_WASTAGE_MENU FOREIGN KEY (MENU_ID) 
        REFERENCES MENU(MENU_ID) ON DELETE CASCADE,
    CONSTRAINT FK_WASTAGE_REC_BY FOREIGN KEY (RECORDED_BY) 
        REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_SERVED_LE_PREP CHECK (FOOD_SERVED <= FOOD_PREPARED),
    CONSTRAINT CHK_WASTED_LE_PREP CHECK (FOOD_WASTED <= FOOD_PREPARED)
);

CREATE INDEX IDX_WASTAGE_MENU ON WASTAGE(MENU_ID);

PROMPT Table WASTAGE created successfully.
